const dictionaries: Record<Language, Dictionary> = { en, es };
let current: Language = "en";

/** Cambia el idioma activo. */
export function setLanguage(language: Language): void {
  current = language;
  document.documentElement.lang = language;
}

/** Devuelve el idioma activo. */
export function getLanguage(): Language {
  return current;
}

/** Busca una clave con puntos dentro de un diccionario. */
function lookup(dictionary: Dictionary, key: string): string | undefined {
  let node: string | Dictionary | undefined = dictionary;
  for (const part of key.split(".")) {
    if (node === undefined || typeof node === "string") {
      return undefined;
    }
    node = node[part];
  }
  return typeof node === "string" ? node : undefined;
}

/** Sustituye {variable} por su valor. */
function interpolate(text: string, vars: Record<string, string | number>): string {
  let result = text;
  for (const name of Object.keys(vars)) {
    result = result.split("{" + name + "}").join(String(vars[name]));
  }
  return result;
}

/** Devuelve el texto traducido de una clave. */
export function t(key: string, vars: Record<string, string | number> = {}): string {
  const text = lookup(dictionaries[current], key) ?? lookup(en, key) ?? key;
  return interpolate(text, vars);
}

/** Aplica las traducciones a los elementos estáticos con data-i18n. */
export function translateStatic(root: ParentNode): void {
  for (const node of root.querySelectorAll<HTMLElement>("[data-i18n]")) {
    node.textContent = t(node.dataset.i18n ?? "");
  }
  for (const node of root.querySelectorAll<HTMLElement>("[data-i18n-label]")) {
    node.setAttribute("aria-label", t(node.dataset.i18nLabel ?? ""));
    node.title = t(node.dataset.i18nLabel ?? "");
  }
}
